@client.on(events.NewMessage(pattern=r'/ban (\d+)', func=lambda e: e.sender_id in ADMIN_USER_IDS))
async def admin_ban_handler(event):
    """Handles banning a user."""
    admin_id = event.sender_id
    try:
        user_to_ban = int(event.pattern_match.group(1))
        if user_to_ban in ADMIN_USER_IDS:
            await event.reply("Cannot ban an admin.")
            return

        if set_user_banned_status(user_to_ban, True):
            logger.info(f"Admin {admin_id} banned user {user_to_ban}")
            await event.reply(get_string(admin_id, "admin_ban_confirm").format(user_to_ban))
        else:
            await event.reply(get_string(admin_id, "admin_ban_fail").format(user_to_ban))
    except Exception as e:
        logger.error(f"Error in /ban command by {admin_id}: {e}")
        await event.reply(get_string(admin_id, "admin_invalid_command"))


