# --- Database Functions ---
def db_connect():
    """Creates a database connection."""
    return sqlite3.connect(DB_NAME)

def db_setup():
    """Sets up the database tables if they don't exist."""
    conn = db_connect()
    cursor = conn.cursor()
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY,
            username TEXT,
            first_name TEXT,
            last_name TEXT,
            language TEXT DEFAULT 'fa',
            is_banned INTEGER DEFAULT 0,
            join_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    ''')
    # Add more tables if needed (e.g., admins)
    conn.commit()
    conn.close()
    logger.info("Database setup complete.")

def get_user_lang(user_id):
    """Gets the user's preferred language."""
    conn = db_connect()
    cursor = conn.cursor()
    cursor.execute('SELECT language FROM users WHERE user_id = ?', (user_id,))
    result = cursor.fetchone()
    conn.close()
    return result[0] if result else 'fa'  # Default to Persian

def update_user_lang(user_id, lang_code):
    """Updates the user's language preference."""
    conn = db_connect()
    cursor = conn.cursor()
    cursor.execute('UPDATE users SET language = ? WHERE user_id = ?', (lang_code, user_id))
    conn.commit()
    conn.close()

def add_or_update_user(user_id, username, first_name, last_name):
    """Adds a new user or updates existing user's info, keeping language and banned status."""
    conn = db_connect()
    cursor = conn.cursor()
    cursor.execute('''
        INSERT INTO users (user_id, username, first_name, last_name)
        VALUES (?, ?, ?, ?)
        ON CONFLICT(user_id) DO UPDATE SET
            username = excluded.username,
            first_name = excluded.first_name,
            last_name = excluded.last_name
    ''', (user_id, username, first_name, last_name))
    conn.commit()
    conn.close()

def is_user_banned(user_id):
    """Checks if a user is banned."""
    conn = db_connect()
    cursor = conn.cursor()
    cursor.execute('SELECT is_banned FROM users WHERE user_id = ?', (user_id,))
    result = cursor.fetchone()
    conn.close()
    return result and result[0] == 1

def set_user_banned_status(user_id, banned_status):
    """Sets the banned status for a user."""
    conn = db_connect()
    cursor = conn.cursor()
    # Ensure user exists before trying to update
    cursor.execute('INSERT OR IGNORE INTO users (user_id) VALUES (?)', (user_id,))
    cursor.execute('UPDATE users SET is_banned = ? WHERE user_id = ?', (1 if banned_status else 0, user_id))
    updated_rows = conn.total_changes # Check if the update actually happened
    conn.commit()
    conn.close()
    # Check if the user existed or was inserted, and then updated
    cursor = db_connect().cursor()
    cursor.execute('SELECT EXISTS(SELECT 1 FROM users WHERE user_id=?)',(user_id,))
    user_exists = cursor.fetchone()[0]
    db_connect().close()
    return user_exists > 0 # Return True if user exists (and thus update likely worked or user was inserted)


def get_all_user_ids(include_banned=False):
    """Gets all user IDs from the database."""
    conn = db_connect()
    cursor = conn.cursor()
    query = 'SELECT user_id FROM users'
    if not include_banned:
        query += ' WHERE is_banned = 0'
    cursor.execute(query)
    results = [row[0] for row in cursor.fetchall()]
    conn.close()
    return results

def count_users():
    """Counts the total number of users."""
    conn = db_connect()
    cursor = conn.cursor()
    cursor.execute('SELECT COUNT(*) FROM users')
    result = cursor.fetchone()
    conn.close()
    return result[0] if result else 0


