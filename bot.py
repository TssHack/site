# --- Admin Broadcast ---
admin_waiting_for_broadcast = set()

@client.on(events.CallbackQuery(pattern=b'admin_broadcast_prompt', func=lambda e: e.sender_id in ADMIN_USER_IDS))
async def admin_broadcast_prompt_callback(event):
    """Prompts admin to send the broadcast message."""
    user_id = event.sender_id
    admin_waiting_for_broadcast.add(user_id)
    await event.edit(get_string(user_id, "admin_broadcast_prompt")) # Edit the panel message
    await event.answer() # Acknowledge callback


@client.on(events.NewMessage(func=lambda e: e.sender_id in admin_waiting_for_broadcast))
async def admin_broadcast_receive_handler(event):
    """Receives the message/media admin wants to broadcast."""
    admin_id = event.sender_id

    if admin_id not in admin_waiting_for_broadcast:
         return # Should not happen based on func filter, but safety check

    admin_waiting_for_broadcast.remove(admin_id) # Process only once

    message_to_broadcast = event.message # This includes text, media, entities, etc.

    user_ids = get_all_user_ids(include_banned=False)
    if not user_ids:
        await event.reply("No users found to broadcast to.")
        return

    count = len(user_ids)
    await event.reply(get_string(admin_id, "admin_broadcast_confirm").format(count))
    logger.info(f"Admin {admin_id} starting broadcast to {count} users.")

    success_count = 0
    blocked_count = 0
    start_time = time.time()

    for user_id in user_ids:
        if user_id == admin_id: # Don't broadcast to self (optional)
             continue
        try:
            # Forwarding is often easier and preserves formatting/media correctly
            # await client.forward_messages(user_id, message_to_broadcast)
            # Or send a copy (if forwarding is not desired or causes issues)
            await client.send_message(user_id, message_to_broadcast)
            success_count += 1
            logger.debug(f"Broadcast sent to {user_id}")
        except UserIsBlockedError:
            logger.warning(f"User {user_id} blocked the bot. Skipping broadcast.")
            blocked_count += 1
        except FloodWaitError as e:
            logger.warning(f"Flood wait of {e.seconds} seconds encountered during broadcast.")
            await asyncio.sleep(e.seconds + 1) # Wait extra second
            # Retry sending to the same user after wait
            try:
                 await client.send_message(user_id, message_to_broadcast)
                 success_count += 1
                 logger.debug(f"Broadcast sent to {user_id} after flood wait.")
            except Exception as retry_e:
                 logger.error(get_string(admin_id, "admin_broadcast_failed_user").format(user_id, retry_e))
        except Exception as e:
            logger.error(get_string(admin_id, "admin_broadcast_failed_user").format(user_id, e))

        # Sleep briefly between messages to avoid hitting limits too quickly
        await asyncio.sleep(0.1) # Adjust sleep time as needed (0.05 to 0.2 is common)

    end_time = time.time()
    duration = end_time - start_time
    logger.info(f"Broadcast finished in {duration:.2f} seconds.")
    await event.reply(get_string(admin_id, "admin_broadcast_done").format(success_count, blocked_count))


