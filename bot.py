@client.on(events.CallbackQuery(pattern=b'setlang_(fa|en)'))
async def set_language_callback(event):
    """Handles language selection callback."""
    user_id = event.sender_id
    lang_code = event.data.decode('utf-8').split('_')[1]

    update_user_lang(user_id, lang_code)
    logger.info(f"User {user_id} changed language to {lang_code}")

    # Use the newly set language for the confirmation message
    confirmation_text = get_string(user_id, "settings_lang_set", lang_code).format(
        get_string(user_id, f"settings_lang_{lang_code}", lang_code) # Get the language name in its own language
    )

    try:
        # Edit the original message to show confirmation
        await event.edit(confirmation_text)
        # Send the main menu again with updated language
        await event.respond(get_string(user_id,"start_welcome", lang_code), buttons=await get_main_menu(user_id))
    except Exception as e:
        logger.error(f"Error updating language message for {user_id}: {e}")
        # Fallback: Answer the callback query simply
        await event.answer(get_string(user_id, "settings_lang_set", lang_code).format(lang_code.upper()))


@client.on(events.NewMessage(pattern='^(?!/).+'))  # Catches non-command messages
async def handle_prompt(event):
    """Handles user prompts for website generation."""
    sender = await event.get_sender()
    user_id = sender.id
    user_prompt = event.raw_text.strip()

    # Ignore empty messages or potential button presses that slipped through
    if not user_prompt:
        return

    # Check if the text matches a menu button again (in case menu handler didn't catch it)
    lang = get_user_lang(user_id)
    if user_prompt in [get_string(user_id, btn, lang) for btn in ["main_menu_button_create", "main_menu_button_settings", "main_menu_button_contact"]]:
        # It's likely a button press, let the main_menu_handler deal with it or ignore
        logger.debug(f"Ignoring likely button press from {user_id}: {user_prompt}")
        return

    # --- User Checks ---
    add_or_update_user(user_id, sender.username, sender.first_name, sender.last_name) # Ensure user exists

    if await is_user_banned(user_id):
        await event.reply(get_string(user_id, "banned_message"))
        return

    logger.info(f"Prompt received from {user_id} ({sender.username}): {user_prompt}")
    msg = await event.reply(get_string(user_id, "creating_website"))

    try:
        # --- Call AI API ---
        async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=120)) as session: # Increased timeout slightly
             # Add headers if your API requires them (e.g., auth tokens)
             headers = {"Content-Type": "application/json"} # Example header
             async with session.post(AI_API_URL, json={"prompt": user_prompt}, headers=headers) as resp:
                if resp.status == 200:
                    html_code = await resp.text()
                else:
                    error_text = await resp.text()
                    logger.error(f"API Error for user {user_id}. Status: {resp.status}, Response: {error_text[:500]}") # Log part of the error
                    await msg.edit(get_string(user_id, "error_creating").format(f"API Status {resp.status}"))
                    return


        # Basic HTML validation (check for <!doctype html>)
        if not html_code or not html_code.strip().lower().startswith("<!doctype html"):
            logger.warning(f"Invalid HTML received for user {user_id}. Response: {html_code[:500]}") # Log part of the invalid response
            await msg.edit(get_string(user_id, "error_invalid_html"))
            return

        # --- Save HTML File ---
        unique_id = str(uuid.uuid4())
        # Store files in a dedicated directory (ensure it exists)
        output_dir = "generated_websites"
        os.makedirs(output_dir, exist_ok=True)
        file_name = f"website_{unique_id[:8]}.html"
        file_path = os.path.join(output_dir, file_name)

        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(html_code)
        logger.info(f"HTML file saved for user {user_id}: {file_path}")

        # --- Send File to User ---
        try:
            await client.send_file(
                event.chat_id,
                file_path,
                caption=get_string(user_id, "website_caption"),
                reply_to=event.id
            )
        except Exception as e:
            logger.error(f"Failed to send file {file_path} to {user_id}: {e}")
            await msg.edit(get_string(user_id, "error_generic")) # Inform user about generic error
            # Don't delete the file yet if sending failed, maybe retry later or log for admin
            return # Stop further processing for this request


        # --- Send WebApp Button ---
        # Construct the web app URL. IMPORTANT: Ensure your web app at WEBAPP_HOST
        # knows how to handle this ID to display the correct preview.
        # This usually means the web app needs access to the generated content,
        # possibly by fetching it from a server endpoint using the unique_id.
        # The current structure implies the web app fetches content independently.
        webapp_url = f"{WEBAPP_HOST}{unique_id}" # Using the full UUID might be safer

        await client.send_message(
            event.chat_id,
            get_string(user_id, "live_preview_prompt"),
            buttons=[[
                # Use KeyboardButtonWebView for inline web apps
                 KeyboardButton(
                    text=get_string(user_id, "view_in_telegram"),
                    url=webapp_url # For simple link button
                 )
                 # Or for integrated webview:
                 # Button.web_app( # requires telethon >= 1.25 approx
                 #    text=get_string(user_id, "view_in_telegram"),
                 #    url=webapp_url
                 # )
                 # Or using the older way if Button.web_app is not available
                 # Button.url( # This just opens the browser
                 #      text=get_string(user_id, "view_in_telegram"),
                 #      url=webapp_url
                 # )
                 # Let's try the KeyboardButtonWebView approach which is standard for bots
                 # This needs to be part of a ReplyKeyboardMarkup or InlineKeyboardMarkup
                 # Sending it standalone is tricky. Let's use an inline button:

            ],[
                 Button.web_app(get_string(user_id, "view_in_telegram"), webapp_url)
            ]],
            reply_to=event.id
        )

        # --- Cleanup ---
        try:
            os.remove(file_path)
            logger.info(f"Cleaned up file: {file_path}")
        except OSError as e:
            logger.error(f"Error removing file {file_path}: {e}")

        # Edit the initial "Creating..." message to indicate completion (optional)
        await msg.delete() # Or edit it to something like "Website generated!"

    except aiohttp.ClientError as e:
        logger.error(f"HTTP Client Error for user {user_id}: {e}")
        await msg.edit(get_string(user_id, "error_creating").format("Connection Error"))
    except asyncio.TimeoutError:
        logger.error(f"Timeout Error for user {user_id} calling API.")
        await msg.edit(get_string(user_id, "error_creating").format("Request Timeout"))
    except Exception as e:
        logger.exception(f"Unhandled error processing prompt for user {user_id}: {e}") # Log full traceback
        await msg.edit(get_string(user_id, "error_generic"))

